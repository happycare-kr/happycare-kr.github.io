  function composeCareRecord(s, opts) {
    const o = opts || {};
    const dt = String((s && s.date) || '');
    const mDay = dt.match(/-(\d{1,2})$/);
    const dayPos = mDay ? Math.max(0, Number(mDay[1]) - 1) : 0;
    const idxNum = Math.abs(Number(o.idx || 0));
    const offNum = Math.abs(Number(o.seedOffset || 0));
    const ptKey = String((s && (s.patientId || s.patientName)) || 'PT');
    const stypeKey = String((s && (s.stype || s.sKind || s.service)) || 'CARE');
    const baseSeed = hash32(ptKey + '|' + dt + '|' + (s && s.start || '') + '|' + stypeKey);
    const seed = (baseSeed ^ Math.imul((dayPos + 1) * 131 + (idxNum + 1) * 977 + offNum * 4099 + 17, 2654435761)) >>> 0;

    let prefix = '';
    const isMan = Boolean(o.isManualMode != null ? o.isManualMode : (
      s && (s.writeMode === 'MANUAL' || s.isManualRecord === true || s.rfidEndMissing === true)
    ));
    if (isMan) {
      prefix = composeManualTagReason(s, seed + offNum);
    } else if (s && s.planStart && s.start && diffMinutesHM(s.planStart, s.start) > 60) {
      prefix = '방문시간(' + s.planStart + '→' + s.start + ')을 사전 협의 조정하여 제공함. ';
    }

    const core = resolveCareSlotText(s, seed);
    return cleanSentence(prefix + applyToneStyle(core.body, seed));
  }

