  function diffMinutesHM(hmA, hmB) {
    const pa = String(hmA || '').trim().match(/^(\d{1,2}):(\d{2})/);
    const pb = String(hmB || '').trim().match(/^(\d{1,2}):(\d{2})/);
    if (!pa || !pb) return 0;
    const ma = Number(pa[1]) * 60 + Number(pa[2]);
    const mb = Number(pb[1]) * 60 + Number(pb[2]);
    let d = Math.abs(mb - ma);
    if (d > 720) d = 1440 - d;
    return d;
  }

  function composeManualTagReason(s, seedInput) {
    const raw = String((s && (s.manualReason || s.rfidFaultReason)) || '').trim();
    const mType = detectManualReasonType(s);
    const seed = (seedInput != null ? seedInput : hash32((s && s.id) + '|' + (s && s.date) + '|' + (s && s.patientName) + '|' + raw)) >>> 0;

    // 1) 사용자가 직접 입력했거나 사유 칩으로 선택된 경우: 입력한 실제 사유 그대로 정중하게 다듬어 반영
    if (raw && !isMachineRfidReason(raw)) {
      const clean = raw.replace(/[.。\s]+$/g, '').trim();
      const nounSkip = /(마음|졸음|아픔|모임|책임|기쁨|슬픔|그림|살림|다짐|받침)$/;
      if (/(함|됨|임|침|짐|김|셈|봄|씀|남|았음|었음|였음|했음|놓침|찍음|없음|있음|다|요)$/.test(clean) && !nounSkip.test(clean)) {
        return clean + '. ';
      }
      const post = josa(clean, '으로/로') + ' 인해';
      if (mType === 'START') return clean + post + ' 시작 태그를 찍지 못해 실제 제공시간 기준으로 수기 작성함. ';
      if (mType === 'END') return clean + post + ' 종료 태그를 찍지 못해 실제 제공시간 기준으로 수기 작성함. ';
      if (mType === 'OVER') return clean + post + ' 계획 시간이 초과되어 실제 제공내역을 수기 작성함. ';
      return clean + post + ' 전자태그를 전송하지 못해 실제 제공내역을 수기 작성함. ';
    }

    // 2) 실제 일정상 시작시각 차이가 60분을 초과한 OVER 케이스만 방문시간 변경 안내
    if (mType === 'OVER' && s && s.planStart && s.start && diffMinutesHM(s.planStart, s.start) > 60) {
      return cleanSentence('방문시간(' + s.planStart + '→' + s.start + ') 변경에 따라 실제 제공시간 기준으로 수기 제공기록지를 작성함.') + ' ';
    }

    // 3) 미입력 기본값: 절대 미발생 사유(병원 등)를 지어내지 않고 확인된 태그 예외 유형만 중립 서술
    const pool = NEUTRAL_REASON_POOLS[mType] || NEUTRAL_REASON_POOLS.BOTH;
    const lead = pickSlot(pool.lead, seed, 0, 11);
    const ev = pickSlot(pool.event, seed, 1, 29);
    const ver = pickSlot(pool.verify, seed, 2, 47);
    const cls = pickSlot(pool.close, seed, 3, 73);
    return cleanSentence(lead + ' ' + ev + ' ' + ver + ' ' + cls) + ' ';
  }

